/** Returns crop info or a sensible fallback */
export function getCropInfo(cropName) {
  if (!cropName) return null;
  const key = cropName.toLowerCase().replace(/[^a-z]/g, "");
  // Try exact match first, then fuzzy
  return (
    CROP_INFO[key] ||
    CROP_INFO[cropName.toLowerCase()] ||
    Object.entries(CROP_INFO).find(([k]) => k.includes(key) || key.includes(k))?.[1] ||
    null
  );
}

/** Sort and return top-K crops from a recommendation result */
export function getTopCrops(cropResult, k = 5) {
  if (!cropResult?.top_crops) return [];
  return cropResult.top_crops.slice(0, k);
}
